// One entry per diagnostic code, in registry order: the build turns each into dist/diagnostics/<code>.html.
//
// - `condition` starts with the condition of the registry table in docs/02-product-spec.md section 3.5,
//   word for word (the unit test checks it), and adds what the code also covers. `drawn` follows the same table.
// - `see`, `why` and `fix` are Markdown.
// - `input` is a minimal input that raises the code, and `outcome` sits right beside it: what running it does,
//   with `because`, the sentence a reviewer reads against the input. With `run: 'node'` the input is an
//   expression calling `validate()`; the build runs it against the packed package (the page shows its output)
//   and the unit test runs it again. With `run: 'browser'` it is a statement list run in a page with the chart
//   functions in scope and `target` an empty element. The browser test runs every input as a chart, once as
//   written and once with `strict: true`, and checks `outcome.field` (the diagnostic's field), `outcome.rows`
//   when given, `outcome.strict` (whether a strict chart throws it from the call) and `outcome.reader` (what the
//   figure shows: `note: …`, `message: …`, `fallback` for the summary in place of the plot, or `nothing`).
//   `sample` gives the registry details the page uses to show the message of a browser-only input; the browser
//   test checks that the line the page shows is one the library printed. `outcome.listed: false` says the code
//   is passed to `onDiagnostic` and printed but not kept in `chart.diagnostics` (a `zoom()` that changes nothing).
// - `cases` (optional) are further inputs that raise the same code, each with a `label`, `run`, `input`,
//   `outcome` and, for the browser, `sample`; the page shows each with what it printed, and the tests run them
//   like the minimal input.

